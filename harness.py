#!/usr/bin/env python3
"""Reliability harness: does the agentic layer actually improve outcomes?

Runs the same queries twice — once with the explanation accepted as written (explain-only),
once through the verify-and-retry loop — and scores pass/fail rather than similarity.

Pass rules
  answerable   : status "answered" AND the explanation verified as grounded
  unanswerable : the system declines (status "no_match" or "caveated"), instead of dressing
                 up a meaningless result

Usage
  python3 harness.py                       # offline, deterministic stub
  python3 harness.py --provider gemini     # live model, needs GEMINI_API_KEY
  python3 harness.py --markdown assets/harness_results.md
"""

import argparse
import json
import os
import sys

from src.agent import run
from src.llm import get_provider
from src.recommender import load_profiles, load_songs

QUERIES = [
    ("answerable", "something chill for studying"),
    ("answerable", "upbeat pop for the gym"),
    ("answerable", "lofi for reading on a rainy day"),
    ("answerable", "popular 90s hits"),
    ("answerable", "slow acoustic songs"),
    ("answerable", "energetic dance music"),
    ("answerable", "quiet sad songs"),
    ("answerable", "2020s pop"),
    ("answerable", "obscure deep cuts"),
    ("answerable", "rock for a road trip"),
    ("answerable", "1940s jazz ballads"),  # jazz exists; the decade does not → caveat
    ("unanswerable", "reggae for the beach"),
    ("unanswerable", "polka death metal"),
    ("unanswerable", "a classical symphony from 1750"),
    ("unanswerable", "bebop from mars"),
    ("unanswerable", "gregorian chant for a cathedral"),
]


def score(expect, result):
    if expect == "answerable":
        ok = result["status"] == "answered" and result["grounding"]["grounded"]
    else:
        ok = result["status"] in ("no_match", "caveated")
    return ok


def evaluate(songs, profiles, provider, guardrails, trace_path):
    rows = []
    for expect, query in QUERIES:
        result = run(query, songs, profiles, provider=provider, guardrails=guardrails,
                     trace_path=trace_path)
        rows.append({
            "expect": expect,
            "query": query,
            "status": result["status"],
            "grounded": result.get("grounding", {}).get("grounded", False),
            "ratio": result.get("grounding", {}).get("ratio", 0.0),
            "attempts": len(result["attempts"]),
            "pass": score(expect, result),
            "title": result.get("recommendation", {}).get("title", "—"),
            "problems": result.get("grounding", {}).get("problems", []),
        })
    return rows


def render_markdown(base_rows, loop_rows, provider_name):
    def cell(row):
        mark = "pass" if row["pass"] else "fail"
        if row["status"] == "no_match":
            return f"{mark} (declined)"
        return f"{mark} ({row['ratio']:.2f}, {row['attempts']} attempt{'s' if row['attempts'] != 1 else ''})"

    lines = [
        "# Reliability harness — explain-only vs verified loop",
        "",
        f"Provider: `{provider_name}`. Generated by `harness.py`.",
        "Pass means: an answerable request got a grounded answer; an unanswerable request was "
        "declined rather than answered anyway.",
        "",
        "| # | Query | Expected | Explain-only | Verified loop |",
        "|---|---|---|---|---|",
    ]
    for i, (base, loop) in enumerate(zip(base_rows, loop_rows), 1):
        lines.append(f"| {i} | {base['query']} | {base['expect']} | {cell(base)} | {cell(loop)} |")

    base_pass = sum(r["pass"] for r in base_rows)
    loop_pass = sum(r["pass"] for r in loop_rows)
    lines += [
        "",
        "## Summary",
        "",
        f"- Explain-only: **{base_pass}/{len(base_rows)}** passed",
        f"- Verified loop: **{loop_pass}/{len(loop_rows)}** passed",
        "",
    ]

    fixed = [b["query"] for b, l in zip(base_rows, loop_rows) if l["pass"] and not b["pass"]]
    broke = [b["query"] for b, l in zip(base_rows, loop_rows) if b["pass"] and not l["pass"]]
    if fixed:
        lines.append("## Fixed by the verified loop")
        lines.append("")
        for q in fixed:
            lines.append(f"- `{q}`")
        lines.append("")
    if broke:
        lines.append("## Regressions")
        lines.append("")
        for q in broke:
            lines.append(f"- `{q}`")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--provider", default="stub-sloppy",
                        help="stub-sloppy (offline demo), stub-careful, or gemini")
    parser.add_argument("--markdown", default=None, help="write the table to this path")
    parser.add_argument("--trace", default="assets/agentic_trace.jsonl")
    args = parser.parse_args()

    songs, profiles = load_songs(), load_profiles()
    provider = get_provider(args.provider)

    if args.trace and os.path.exists(args.trace):
        os.remove(args.trace)

    base_rows = evaluate(songs, profiles, provider, guardrails=False, trace_path=args.trace)
    loop_rows = evaluate(songs, profiles, provider, guardrails=True, trace_path=args.trace)

    report = render_markdown(base_rows, loop_rows, provider.name)
    print(report)

    if args.markdown:
        os.makedirs(os.path.dirname(os.path.abspath(args.markdown)), exist_ok=True)
        with open(args.markdown, "w", encoding="utf-8") as handle:
            handle.write(report + "\n")
        print(f"\nwrote {args.markdown}")

    return 0 if all(r["pass"] for r in loop_rows) else 1


if __name__ == "__main__":
    sys.exit(main())
